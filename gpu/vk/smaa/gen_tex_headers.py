"""Pack official SMAA Area/Search DDS payloads into compact C headers for vk_smaa.cpp."""
import pathlib
import struct

here = pathlib.Path(__file__).resolve().parent


def dump_array(path: pathlib.Path, var: str, data: bytes, per=16):
    lines = [f"// Generated by gen_tex_headers.py — do not edit.", f"static const unsigned char {var}[] = {{"]
    for i in range(0, len(data), per):
        chunk = data[i : i + per]
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(path.name, len(data), "bytes")


def dds_payload(path: pathlib.Path) -> tuple[int, int, bytes]:
    b = path.read_bytes()
    assert b[:4] == b"DDS "
    h = b[4:128]
    height, width = struct.unpack_from("<2I", h, 8)
    fourcc = struct.unpack_from("<4s", h, 84)[0]
    off = 148 if fourcc == b"DX10" else 128
    return width, height, b[off:]


# AreaTex DX9: 160 x 560, R8G8
aw, ah, area = dds_payload(here / "AreaTexDX9.dds")
assert (aw, ah) == (160, 560) and len(area) == aw * ah * 2, (aw, ah, len(area))
dump_array(here / "area_tex_bytes.h", "SMAA_AREA_TEX", area)

# SearchTex: 64 x 16, R8
sw, sh, search = dds_payload(here / "SearchTex.dds")
assert (sw, sh) == (64, 16) and len(search) == sw * sh, (sw, sh, len(search))
dump_array(here / "search_tex_bytes.h", "SMAA_SEARCH_TEX", search)

(here / "smaa_tex_sizes.h").write_text(
    f"// Generated by gen_tex_headers.py — do not edit.\n"
    f"#pragma once\n"
    f"#define SMAA_AREATEX_WIDTH {aw}\n"
    f"#define SMAA_AREATEX_HEIGHT {ah}\n"
    f"#define SMAA_SEARCHTEX_WIDTH {sw}\n"
    f"#define SMAA_SEARCHTEX_HEIGHT {sh}\n",
    encoding="utf-8",
)
print("ok")
